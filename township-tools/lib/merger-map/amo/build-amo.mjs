// Builds the ITA website merger map.
//
// AMO's page editor (CKEditor) mangles inline <script> code that contains
// "<" characters, so the map's style, markup and code are served from this
// app as public/merger-map/embed.js. The block pasted into AMO is just a
// container div plus a <script src> tag, and never needs re-pasting when the
// map code changes — redeploying Township Tools updates it.
//
// Source of truth: amo-template.html (style + #ita-mm markup + script).
//
// Usage (from township-tools/):
//   node lib/merger-map/amo/build-amo.mjs "../../ita-amo-management/Site Pages/ITA_merger_meeting_map.html"
// Writes public/merger-map/embed.js and the AMO paste block (path argument).
import fs from 'fs';

const EMBED_URL = 'https://township-tools.vercel.app/merger-map/embed.js';

const src = fs.readFileSync(new URL('../indiana-counties.ts', import.meta.url), 'utf8');
const arr = JSON.parse(src.slice(src.indexOf('= [') + 2, src.lastIndexOf(']') + 1).replace(/,\s*\]$/, ']'));
const vb = src.match(/INDIANA_VIEWBOX = '([^']+)'/)[1];
const compact = '[\n' + arr.map((c) => JSON.stringify([c.name, c.d, c.cx, c.cy])).join(',\n') + '\n  ]';

const t = fs
  .readFileSync(new URL('./amo-template.html', import.meta.url), 'utf8')
  .replace('__COUNTIES__', compact)
  .replace('__VIEWBOX__', vb);

const between = (s, a, b) => {
  const i = s.indexOf(a);
  const j = s.indexOf(b, i + a.length);
  if (i < 0 || j < 0) throw new Error(`template missing ${a} … ${b}`);
  return s.slice(i + a.length, j);
};
const css = between(t, '<style type="text/css">', '</style>').trim();
const markupFull = t.slice(t.indexOf('<div id="ita-mm">'), t.indexOf('<script type="text/javascript">')).trim();
// Inner markup of #ita-mm (the outer div is created by the embed script).
const markup = markupFull.replace(/^<div id="ita-mm">/, '').replace(/<\/div>\s*$/, '').trim();
const code = between(t, '<script type="text/javascript">', '</script>').trim();

const js = `/* ITA Township Merger Meeting Map — generated by lib/merger-map/amo/build-amo.mjs. Do not edit by hand. */
(function(){
  var host = document.getElementById("ita-merger-map");
  if (!host || host.getAttribute("data-mm-ready")) return;
  host.setAttribute("data-mm-ready", "1");
  var style = document.createElement("style");
  style.type = "text/css";
  style.appendChild(document.createTextNode(${JSON.stringify(css)}));
  (document.head || document.getElementsByTagName("head")[0]).appendChild(style);
  host.removeAttribute("style");
  host.innerHTML = "";
  var root = document.createElement("div");
  root.id = "ita-mm";
  root.innerHTML = ${JSON.stringify(markup)};
  host.appendChild(root);

${code}
})();
`;
const outJs = new URL('../../../public/merger-map/embed.js', import.meta.url);
fs.mkdirSync(new URL('.', outJs), { recursive: true });
fs.writeFileSync(outJs, js);

const amo = `<!-- ITA Township Merger Meeting Map -->
<!-- Paste into the AMO page in Source mode. The map is drawn by the script below, -->
<!-- which is hosted on Township Tools, so this block never needs to change. -->
<!-- Lydia edits with the "Edit map (ITA staff)" button under the map, or by adding #edit to the page address. -->
<div id="ita-merger-map" style="background:#FBF8EF;padding:40px 15px;text-align:center;font-family:'Instrument Sans',Arial,Helvetica,sans-serif;font-size:17px;color:#555555;">Loading the merger meeting map...</div>
<script type="text/javascript" src="${EMBED_URL}"></script>
`;
fs.writeFileSync(process.argv[2] || 'ITA_merger_meeting_map.html', amo);
console.log(arr.length, 'counties; embed.js', (js.length / 1024).toFixed(0) + 'KB');
